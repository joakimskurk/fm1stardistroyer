"""Writes firmware/src/sd_logo.h: the Star Distroyer logo, cut from the user's mockup (docs/sd/ui/
mockup_workstation.webp, the "/// STAR DISTROYER" in its top left), as 4-bit masks for the 240 x 240 screen.

A pixel is 4 bits: 0 nothing, 1..7 the logo's ice white at that coverage (of 7), 9..15 its red (the slashes) at
coverage 1..7. Two pixels a byte, the left one high; a row starts on a byte.
    SD_LOGO_STAR       "/// STAR"     the splash's first line
    SD_LOGO_DISTROYER  "DISTROYER"    its second, at the same scale
    SD_LOGO_HEADER     the whole line, small: the main screen's top left
Needs Pillow (python3 -m pip install pillow)."""
import os
from PIL import Image

HERE = os.path.dirname(__file__)
SRC = os.path.join(HERE, "..", "docs", "sd", "ui", "mockup_workstation.webp")
OUT = os.path.join(HERE, "..", "firmware", "src", "sd_logo.h")
TOP, BOTTOM = 12, 44                    # the logo's rows in the mockup (glyphs at 14..41)
SLASH_STAR = (40, 256)                  # "///" 42..107 and "STAR" 125..254
DISTROYER = (282, 594)                  # 284..592
SPLASH_W = 224                          # DISTROYER's width on the splash: the scale for both lines
HEADER_W = 168


def mask(img, x0, x1, width):
    crop = img.crop((x0, TOP, x1, BOTTOM))
    h = max(1, round(crop.height * width / crop.width))
    crop = crop.resize((width, h), Image.LANCZOS)
    px = crop.load()
    out = []
    for y in range(h):
        row = []
        for x in range(width):
            r, g, b = px[x, y][:3]
            if r > 70 and r > 2.2 * max(g, b):          # the red slashes
                a = round(7 * min(1.0, max(0.0, (r - 25) / 170)))
                row.append(8 + a if a else 0)
            else:                                       # the ice-white letters
                a = round(7 * min(1.0, max(0.0, ((r + g + b) / 3 - 22) / 190)))
                row.append(a)
        out.append(row)
    return width, h, out


def emit(f, name, m):
    w, h, rows = m
    data = []
    for row in rows:
        row = row + [0] * (len(row) % 2)
        data += [row[i] << 4 | row[i + 1] for i in range(0, len(row), 2)]
    f.write("static const uint8_t %s_PX[%d] = {\n" % (name, len(data)))
    for i in range(0, len(data), 20):
        f.write("    " + ", ".join("%d" % v for v in data[i:i + 20]) + ",\n")
    f.write("};\nstatic const SdLogo %s = {%d, %d, %s_PX};\n\n" % (name, w, h, name))


def main():
    img = Image.open(SRC).convert("RGB")
    scale = SPLASH_W / (DISTROYER[1] - DISTROYER[0])
    with open(OUT, "w") as f:
        f.write("/* SPDX-License-Identifier: GPL-3.0-only */\n")
        f.write("/* Generated by tools/gen_logo.py from docs/sd/ui/mockup_workstation.webp. Do not edit. */\n")
        f.write("#ifndef SD_LOGO_H\n#define SD_LOGO_H\n#include <stdint.h>\n\n")
        f.write("typedef struct { uint16_t w, h; const uint8_t *px; } SdLogo;   /* 4 bits a pixel, see the script */\n\n")
        emit(f, "SD_LOGO_STAR", mask(img, *SLASH_STAR, round((SLASH_STAR[1] - SLASH_STAR[0]) * scale)))
        emit(f, "SD_LOGO_DISTROYER", mask(img, *DISTROYER, SPLASH_W))
        emit(f, "SD_LOGO_HEADER", mask(img, SLASH_STAR[0], DISTROYER[1], HEADER_W))
        f.write("#endif\n")
    print("gen_logo -> %s" % os.path.normpath(OUT))


if __name__ == "__main__":
    main()
